"""Explicit, inspectable interlocks for simulated switching operations.

These checks are engineering decision-support rules, not a protection relay,
permit-to-work system, or safety-rated switching authority. A topology model
cannot prove voltage absence, phase synchronism, grounding integrity, or human
clearance. Such facts must be supplied as traceable permits by the caller.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol
from uuid import UUID

from .models import (
    EquipmentRecord,
    NetworkSnapshot,
    OperatingScenario,
    OperatingTopologyResult,
    SwitchPosition,
)


@dataclass(frozen=True, slots=True)
class OperationPermit:
    """Traceable evidence supplied by an authorized external workflow.

    The values are references, not Boolean assertions generated by PFA. A
    non-empty reference records that an external process provided evidence;
    PFA does not validate the external measurement or authorization itself.
    """

    operator_id: str | None = None
    authorization_reference: str | None = None
    synchronism_check_reference: str | None = None
    voltage_absence_test_reference: str | None = None

    def __post_init__(self) -> None:
        for name in (
            "operator_id",
            "authorization_reference",
            "synchronism_check_reference",
            "voltage_absence_test_reference",
        ):
            value = getattr(self, name)
            if value is not None and (not isinstance(value, str) or not value.strip()):
                raise ValueError(f"{name} must be a non-empty string or None.")

    def to_dict(self) -> dict[str, str | None]:
        return {
            "operator_id": self.operator_id,
            "authorization_reference": self.authorization_reference,
            "synchronism_check_reference": self.synchronism_check_reference,
            "voltage_absence_test_reference": self.voltage_absence_test_reference,
        }


@dataclass(frozen=True, slots=True)
class InterlockFinding:
    code: str
    message: str
    blocking: bool = True
    equipment_id: UUID | None = None
    bus_ids: tuple[UUID, ...] = ()


@dataclass(frozen=True, slots=True)
class InterlockContext:
    snapshot: NetworkSnapshot
    scenario: OperatingScenario
    topology: OperatingTopologyResult
    equipment: EquipmentRecord
    target_position: SwitchPosition
    permit: OperationPermit

    @property
    def connected_bus_ids(self) -> frozenset[UUID]:
        return frozenset(
            connection.bus_id
            for connection in self.snapshot.connections
            if connection.terminal_id in self.equipment.terminal_ids
        )


class InterlockRule(Protocol):
    """Port implemented by built-in or project-specific interlock policies."""

    def evaluate(self, context: InterlockContext) -> tuple[InterlockFinding, ...]: ...


class GroundSwitchCloseInterlock:
    """Block grounding-switch closure onto a source-reachable bus.

    Even when the graph reports every attached bus de-energized, closing a
    grounding switch requires a traceable voltage-absence test reference.
    """

    def evaluate(self, context: InterlockContext) -> tuple[InterlockFinding, ...]:
        if (
            not context.equipment.is_grounding_switch
            or context.target_position is not SwitchPosition.CLOSED
        ):
            return ()
        connected = context.connected_bus_ids
        energized = context.topology.energized_bus_ids.intersection(connected)
        findings: list[InterlockFinding] = []
        if energized:
            findings.append(
                InterlockFinding(
                    code="GROUND_SWITCH_CLOSE_ON_ENERGIZED_BUS",
                    message=(
                        "Grounding-switch closure is blocked because one or more connected "
                        "buses are source-reachable in the operating-topology model."
                    ),
                    equipment_id=context.equipment.equipment_id,
                    bus_ids=tuple(sorted(energized, key=str)),
                )
            )
        if not context.permit.voltage_absence_test_reference:
            findings.append(
                InterlockFinding(
                    code="GROUND_SWITCH_REQUIRES_VOLTAGE_ABSENCE_EVIDENCE",
                    message=(
                        "A traceable external voltage-absence test reference is required "
                        "before a grounding-switch closure can be simulated."
                    ),
                    equipment_id=context.equipment.equipment_id,
                    bus_ids=tuple(sorted(connected, key=str)),
                )
            )
        return tuple(findings)


class CloseOntoGroundedBusInterlock:
    """Prevent normal switch closure when any connected bus is modeled grounded."""

    def evaluate(self, context: InterlockContext) -> tuple[InterlockFinding, ...]:
        if (
            context.equipment.is_grounding_switch
            or context.target_position is not SwitchPosition.CLOSED
        ):
            return ()
        grounded = {
            item.bus_id for item in context.topology.buses if item.grounded
        }.intersection(context.connected_bus_ids)
        if not grounded:
            return ()
        return (
            InterlockFinding(
                code="CLOSE_ON_GROUNDED_BUS",
                message=(
                    "Switch closure is blocked because at least one connected bus is marked "
                    "grounded in the operating scenario."
                ),
                equipment_id=context.equipment.equipment_id,
                bus_ids=tuple(sorted(grounded, key=str)),
            ),
        )


class ParallelEnergizedIslandsInterlock:
    """Require external synchronism evidence before joining live islands."""

    def evaluate(self, context: InterlockContext) -> tuple[InterlockFinding, ...]:
        if (
            context.equipment.is_grounding_switch
            or context.target_position is not SwitchPosition.CLOSED
        ):
            return ()
        bus_results = {item.bus_id: item for item in context.topology.buses}
        energized_islands = {
            bus_results[bus_id].island_id
            for bus_id in context.connected_bus_ids
            if bus_id in bus_results and bus_results[bus_id].source_reachable
        }
        if len(energized_islands) <= 1 or context.permit.synchronism_check_reference:
            return ()
        return (
            InterlockFinding(
                code="PARALLEL_ENERGIZED_ISLANDS_REQUIRE_SYNCHRONISM_EVIDENCE",
                message=(
                    "The operation would join distinct source-reachable islands. A traceable "
                    "external synchronism-check reference is required."
                ),
                equipment_id=context.equipment.equipment_id,
                bus_ids=tuple(sorted(context.connected_bus_ids, key=str)),
            ),
        )


def default_interlock_rules() -> tuple[InterlockRule, ...]:
    """Return the deterministic baseline interlock policy."""
    return (
        GroundSwitchCloseInterlock(),
        CloseOntoGroundedBusInterlock(),
        ParallelEnergizedIslandsInterlock(),
    )
